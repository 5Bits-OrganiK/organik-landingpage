const setLanguage = (language) => {
  const dictionary = translations[language] ?? translations.en;
  document.documentElement.lang = language;
  localStorage.setItem("organik-language", language);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = getValue(dictionary, element.dataset.i18n) ?? "";
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = getValue(dictionary, element.dataset.i18nPlaceholder) ?? "";
  });

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.language === language);
  });

  document.querySelectorAll("[data-video-id]").forEach((iframe) => {
    const title = iframe.title;
    const videoId = iframe.dataset.videoId;
    iframe.src = `https://www.youtube.com/embed/${videoId}`;
    iframe.srcdoc = buildVideoPreview(videoId, title);
  });
};

const navToggle = document.querySelector(".nav-toggle");
const navPanel = document.querySelector(".nav-panel");

navToggle?.addEventListener("click", () => {
  const isOpen = navPanel.classList.toggle("nav-panel--open");
  navToggle.setAttribute("aria-expanded", String(isOpen));
});

document.querySelectorAll(".nav-panel a, .brand").forEach((link) => {
  link.addEventListener("click", () => {
    navPanel.classList.remove("nav-panel--open");
    navToggle?.setAttribute("aria-expanded", "false");
  });
});

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

setLanguage(localStorage.getItem("organik-language") || "en");
